#include <stdio.h>

int main(){
    //Store the letter N in a variable and print:
    char a = 'N';
    printf("The letter is : %c\n",a);
    

    //Store 20 in an int and print:

    int num = 20;
    printf("The number is: %d\n", num);

    //Favourite number

    int fav = 100;
    printf("My fav num is: %d\n",fav);

    //Store 3.14 in a float and print:

    double dig = 3.14;
    printf("The float is: %.8lf\n",dig);


    return 0;

    

}